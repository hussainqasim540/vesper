#!/usr/bin/env python3
"""Render Vesper's glyph atlas from Inter into src/font_data.h.

Inter (OFL-1.1, https://github.com/rsms/inter) is QuisLab's typeface. The
atlas is an 8-bit alpha image plus per-glyph metrics for a few pixel sizes;
the C side (src/font.c) draws text from it with no font engine on the console.

    python3 tools/make_font.py [fonts_dir]

fonts_dir defaults to ~/Library/Fonts and must hold Inter_18pt-Regular.ttf and
Inter_24pt-SemiBold.ttf. The output is committed, so the build needs no Python.
"""
import os
import sys

from PIL import Image, ImageFont

CHARS = (
    "".join(chr(c) for c in range(32, 127))
    + "àèéìòùÀÈÉÌÒÙçÇ·…–—‘’“”°×«»"
)

# (C name, file, pixel size)
FACES = [
    ("FONT_SMALL", "Inter_18pt-Regular.ttf", 15),
    ("FONT_BODY", "Inter_18pt-Regular.ttf", 20),
    ("FONT_TITLE", "Inter_24pt-SemiBold.ttf", 30),
]
ATLAS_W = 512


def main():
    fonts_dir = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser("~/Library/Fonts")
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "src", "font_data.h")

    glyphs = []  # (face index, codepoint, image, x offset, y offset, advance)
    faces = []
    for fi, (name, file, size) in enumerate(FACES):
        font = ImageFont.truetype(os.path.join(fonts_dir, file), size)
        ascent, descent = font.getmetrics()
        faces.append((name, size, ascent, descent))
        for ch in CHARS:
            left, top, right, bottom = font.getbbox(ch, anchor="ls")
            adv = font.getlength(ch)
            w, h = max(right - left, 0), max(bottom - top, 0)
            img = Image.new("L", (w, h), 0)
            if w and h:
                from PIL import ImageDraw
                ImageDraw.Draw(img).text((-left, -top), ch, font=font, fill=255, anchor="ls")
            glyphs.append((fi, ord(ch), img, left, top, adv))

    # Shelf packing, tallest first.
    order = sorted(range(len(glyphs)), key=lambda i: -glyphs[i][2].size[1])
    x = y = row_h = 0
    pos = {}
    for i in order:
        w, h = glyphs[i][2].size
        if x + w + 1 > ATLAS_W:
            x, y, row_h = 0, y + row_h + 1, 0
        pos[i] = (x, y)
        x += w + 1
        row_h = max(row_h, h)
    atlas_h = y + row_h
    atlas_h = 1 << (atlas_h - 1).bit_length()  # power of two, for GLES2
    atlas = Image.new("L", (ATLAS_W, atlas_h), 0)
    for i, (x, y) in pos.items():
        atlas.paste(glyphs[i][2], (x, y))

    with open(out, "w") as f:
        f.write("/* Generated by tools/make_font.py from Inter (OFL-1.1,\n")
        f.write(" * https://github.com/rsms/inter). Do not edit. */\n")
        f.write("#include <stdint.h>\n\n")
        f.write(f"#define FONT_ATLAS_W {ATLAS_W}\n#define FONT_ATLAS_H {atlas_h}\n")
        f.write(f"#define FONT_FACES {len(FACES)}\n")
        f.write(f"#define FONT_GLYPHS_PER_FACE {len(CHARS)}\n\n")
        f.write("struct font_face_data { int size, ascent, descent; };\n")
        f.write("struct font_glyph_data { uint32_t cp; int16_t x, y, w, h, ox, oy; float adv; };\n\n")
        f.write("static const struct font_face_data font_faces[FONT_FACES] = {\n")
        for name, size, ascent, descent in faces:
            f.write(f"    {{{size}, {ascent}, {descent}}}, /* {name} */\n")
        f.write("};\n\n")
        f.write("static const struct font_glyph_data font_glyphs[FONT_FACES][FONT_GLYPHS_PER_FACE] = {\n")
        for fi in range(len(FACES)):
            f.write("  {\n")
            for i, g in enumerate(glyphs):
                if g[0] != fi:
                    continue
                x, y = pos[i]
                w, h = g[2].size
                f.write(f"    {{{g[1]}, {x}, {y}, {w}, {h}, {g[3]}, {g[4]}, {g[5]:.2f}f}},\n")
            f.write("  },\n")
        f.write("};\n\n")
        data = atlas.tobytes()
        f.write("static const uint8_t font_atlas[FONT_ATLAS_W * FONT_ATLAS_H] = {\n")
        for i in range(0, len(data), 32):
            f.write("  " + ",".join(str(b) for b in data[i:i + 32]) + ",\n")
        f.write("};\n")
    print(f"{out}: {len(glyphs)} glyphs, atlas {ATLAS_W}x{atlas_h}")


if __name__ == "__main__":
    main()
